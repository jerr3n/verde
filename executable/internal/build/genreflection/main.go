// Command genreflection writes reflection.json, the part of rbx-dom's reflection database
// that a place file needs: what each property is saved as, and each enum's numbers.
// Run it with `go generate ./internal/build` to pick up new Roblox classes.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"slices"
	"strings"
)

const (
	databaseURL = "https://raw.githubusercontent.com/rojo-rbx/rbx-dom/master/rbx_dom_lua/src/database.json"
	licenseURL  = "https://raw.githubusercontent.com/rojo-rbx/rbx-dom/master/LICENSE.txt"
)

type rawDatabase struct {
	Version []int               `json:"Version"`
	Classes map[string]rawClass `json:"Classes"`
	Enums   map[string]struct {
		Items map[string]int64 `json:"items"`
	} `json:"Enums"`
}

type rawClass struct {
	Superclass string             `json:"Superclass"`
	Properties map[string]rawProp `json:"Properties"`
}

type rawProp struct {
	DataType struct {
		Value string `json:"Value"`
		Enum  string `json:"Enum"`
	} `json:"DataType"`
	Kind struct {
		Canonical *struct {
			// "Serializes", "DoesNotSerialize", {"SerializesAs": name} or {"Migrate": ...}
			Serialization json.RawMessage `json:"Serialization"`
		} `json:"Canonical"`
		Alias *struct {
			AliasFor string `json:"AliasFor"`
		} `json:"Alias"`
	} `json:"Kind"`
}

type class struct {
	Super string          `json:"super,omitempty"`
	Props map[string]prop `json:"props,omitempty"`
}

type prop struct {
	As   string `json:"as,omitempty"` // the name it's saved under, if that's not its own
	Type string `json:"type"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genreflection:", err)
		os.Exit(1)
	}
}

func run() error {
	raw, err := download(databaseURL)
	if err != nil {
		return err
	}
	var db rawDatabase
	if err := json.Unmarshal(raw, &db); err != nil {
		return fmt.Errorf("database: %w", err)
	}
	license, err := download(licenseURL)
	if err != nil {
		return err
	}

	out, err := convert(db)
	if err != nil {
		return err
	}
	if err := os.WriteFile("reflection.json", out, 0o644); err != nil {
		return err
	}
	return os.WriteFile("reflection.LICENSE", license, 0o644)
}

func download(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// find looks for a property on a class and then on what it inherits from.
func find(db rawDatabase, className, name string) (rawProp, bool) {
	for className != "" {
		c, ok := db.Classes[className]
		if !ok {
			return rawProp{}, false
		}
		if p, ok := c.Properties[name]; ok {
			return p, true
		}
		className = c.Superclass
	}
	return rawProp{}, false
}

// saved works out what a property is written as. ok is false if Roblox doesn't save it.
//
// A migrated property is written under its own name, because Roblox still reads old files
// and turns it into the new property, like Decal.Texture into TextureContent.
func saved(db rawDatabase, className, name string) (prop, bool, error) {
	p, ok := find(db, className, name)
	if !ok {
		return prop{}, false, fmt.Errorf("%s.%s not found", className, name)
	}
	target := name
	if p.Kind.Alias != nil {
		target = p.Kind.Alias.AliasFor
		if p, ok = find(db, className, target); !ok || p.Kind.Canonical == nil {
			return prop{}, false, fmt.Errorf("%s.%s is an alias for %s, which isn't a real property", className, name, target)
		}
	}
	if p.Kind.Canonical == nil {
		return prop{}, false, fmt.Errorf("%s.%s has an unknown kind", className, name)
	}

	var how string
	if json.Unmarshal(p.Kind.Canonical.Serialization, &how) == nil && how == "DoesNotSerialize" {
		return prop{}, false, nil
	}
	var as struct {
		SerializesAs string `json:"SerializesAs"`
	}
	if json.Unmarshal(p.Kind.Canonical.Serialization, &as) == nil && as.SerializesAs != "" {
		target = as.SerializesAs
		if p, ok = find(db, className, target); !ok {
			return prop{}, false, fmt.Errorf("%s.%s is saved as %s, which doesn't exist", className, name, target)
		}
	}

	out := prop{Type: p.DataType.Value}
	if p.DataType.Enum != "" {
		out.Type = "Enum"
	}
	if out.Type == "" {
		return prop{}, false, fmt.Errorf("%s.%s has no type", className, name)
	}
	if target != name {
		out.As = target
	}
	return out, true, nil
}

// convert writes one class or enum to a line, sorted, so an update is a readable diff.
func convert(db rawDatabase) ([]byte, error) {
	var out bytes.Buffer
	version := make([]string, len(db.Version))
	for i, part := range db.Version {
		version[i] = fmt.Sprint(part)
	}
	fmt.Fprintf(&out, "{\n\"version\": %q,\n", strings.Join(version, "."))
	out.WriteString("\"source\": \"Generated by genreflection from rbx-dom. See reflection.LICENSE.\",\n")

	out.WriteString("\"classes\": {\n")
	classNames := sortedKeys(db.Classes)
	for i, className := range classNames {
		raw := db.Classes[className]
		c := class{Super: raw.Superclass, Props: map[string]prop{}}
		for name := range raw.Properties {
			p, ok, err := saved(db, className, name)
			if err != nil {
				return nil, err
			}
			if ok {
				c.Props[name] = p
			}
		}
		if err := writeEntry(&out, className, c, i == len(classNames)-1); err != nil {
			return nil, err
		}
	}
	out.WriteString("},\n\"enums\": {\n")
	enumNames := sortedKeys(db.Enums)
	for i, enumName := range enumNames {
		if err := writeEntry(&out, enumName, db.Enums[enumName].Items, i == len(enumNames)-1); err != nil {
			return nil, err
		}
	}
	out.WriteString("}\n}\n")
	return out.Bytes(), nil
}

func writeEntry(out *bytes.Buffer, name string, value any, last bool) error {
	encoded, err := json.Marshal(value)
	if err != nil {
		return err
	}
	fmt.Fprintf(out, "%q: %s", name, encoded)
	if !last {
		out.WriteByte(',')
	}
	out.WriteByte('\n')
	return nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
