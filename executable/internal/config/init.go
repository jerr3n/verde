package config

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"go.yaml.in/yaml/v4"
)

// initTemplate is the config that `verde init` writes. %s is the project name.
const initTemplate = `# This file is automatically generated by Verde.
version: 0
name: %s
serve:
  address: 127.0.0.1 # or localhost or 0.0.0.0
  port: 45678
  placeIds: [] # places allowed to connect, or empty to allow any place
sync:
  instances:
    - instance: ReplicatedStorage
      path: src/shared
    - instance: ServerScriptService
      path: src/server
    - instance: StarterPlayer/StarterPlayerScripts
      path: src/local
    - instance: StarterGui
      path: src/gui
    - instance: Workspace
      path: src/workspace
    - instance: ReplicatedFirst
      path: src/first
    - instance: ServerStorage
      path: src/storage
    - instance: Lighting
      path: src/lighting
ignore:
  paths: ["**/*.tmp", "**/.DS_Store"]
  instances: ["Workspace/Camera", "Workspace/Terrain"]

conflicts:
  onConnect: disk # disk | studio | interactive
`

// Init writes a new config file at path, and makes its sync folders. The project name is the name of the folder that holds path.
// Init does not change a folder that already exists.
// If the config file already exists, Init changes nothing and returns an error that matches fs.ErrExist.
func Init(path string) error {
	if err := writeInitFile(path); err != nil {
		return err
	}
	if err := makeSyncFolders(path); err != nil {
		// Remove the config, so that `verde init` can run again after the user fixes the problem.
		os.Remove(path)
		return err
	}
	return nil
}

// makeSyncFolders makes each sync folder in the config at path.
// os.Root refuses each path that goes outside the project, also through a symlink.
func makeSyncFolders(path string) error {
	cfg, err := Load(path)
	if err != nil {
		return err
	}

	root, err := os.OpenRoot(cfg.Root)
	if err != nil {
		return err
	}
	defer root.Close()

	for _, entry := range cfg.Sync.Instances {
		if err := root.MkdirAll(entry.Path, 0o755); err != nil {
			return fmt.Errorf("create %s: %w", entry.Path, err)
		}
	}
	return nil
}

// writeInitFile writes initTemplate to path. It does not replace a file that already exists.
func writeInitFile(path string) error {
	abs, err := filepath.Abs(path)
	if err != nil {
		return fmt.Errorf("resolve %s: %w", path, err)
	}

	// Encode the name as YAML, because a folder name can hold characters such as ':' or '#'.
	name, err := yaml.Marshal(filepath.Base(filepath.Dir(abs)))
	if err != nil {
		return err
	}

	// O_EXCL does the check and the create in one step.
	// Thus this call cannot replace a file that another process makes between the two steps.
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("%w: %s", fs.ErrExist, path)
	}
	if err != nil {
		return err
	}

	_, err = fmt.Fprintf(file, initTemplate, bytes.TrimSpace(name))
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		// Remove the file, so that a config that is only half written does not stay.
		os.Remove(path)
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
