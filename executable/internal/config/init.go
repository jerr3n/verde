package config

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"go.yaml.in/yaml/v4"
)

// initTemplate is the config `verde init` writes. %s is the project name.
const initTemplate = `# This file is automatically generated by Verde.
version: 0
name: %s
serve:
  address: 127.0.0.1 # or localhost or 0.0.0.0
  port: 45678
  placeIds: [] # places allowed to connect, or empty to allow any place
sync:
  - instance: ReplicatedStorage
    path: src/shared
  - instance: ServerScriptService
    path: src/server
  - instance: StarterPlayer/StarterPlayerScripts
    path: src/local
  - instance: StarterGui
    path: src/gui
  - instance: Workspace
    path: src/workspace
  - instance: ReplicatedFirst
    path: src/first
  - instance: ServerStorage
    path: src/storage
  - instance: Lighting
    path: src/lighting
ignore:
  paths: ["**/*.tmp", "**/.DS_Store"]
  instances: ["Workspace/Camera", "Workspace/Terrain"]

conflicts:
  onConnect: disk # disk | studio | interactive
`

// Init writes a new config file at path, named after the folder it's in, and creates
// its sync folders. Folders that already exist are left as they are. If the file
// already exists, nothing changes and the error matches fs.ErrExist.
func Init(path string) error {
	if err := writeInitFile(path); err != nil {
		return err
	}
	if err := makeSyncFolders(path); err != nil {
		os.Remove(path) // So that `verde init` can run again once this is fixed.
		return err
	}
	return nil
}

// makeSyncFolders creates every sync folder in the config at path. os.Root refuses
// anything that leaves the project, including through symlinks.
func makeSyncFolders(path string) error {
	cfg, err := Load(path)
	if err != nil {
		return err
	}

	root, err := os.OpenRoot(cfg.Root)
	if err != nil {
		return err
	}
	defer root.Close()

	for _, entry := range cfg.Sync {
		if err := root.MkdirAll(entry.Path, 0o755); err != nil {
			return fmt.Errorf("create %s: %w", entry.Path, err)
		}
	}
	return nil
}

func writeInitFile(path string) error {
	abs, err := filepath.Abs(path)
	if err != nil {
		return fmt.Errorf("resolve %s: %w", path, err)
	}

	// Encoded as YAML, because a folder name can contain characters like ':' or '#'.
	name, err := yaml.Marshal(filepath.Base(filepath.Dir(abs)))
	if err != nil {
		return err
	}

	// O_EXCL makes the existence check and the create one step, so this can't
	// overwrite a file that appears in between.
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("%w: %s", fs.ErrExist, path)
	}
	if err != nil {
		return err
	}

	_, err = fmt.Fprintf(file, initTemplate, bytes.TrimSpace(name))
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		os.Remove(path) // Don't leave half a config behind.
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
